'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8').replace(/\r\n/g, '\n');
const licensePaths = [
  ...fs.readdirSync(path.join(root, 'app/vendor/licenses')).filter(n => n.endsWith('.txt')).sort().map(n => 'app/vendor/licenses/' + n),
  ...fs.readdirSync(path.join(root, 'app/assets/fonts')).filter(n => /OFL\.txt$/.test(n)).sort().map(n => 'app/assets/fonts/' + n)
];
const thirdParty = read('THIRD-PARTY.md') + '\n\n' + licensePaths.map(name => '\n===== ' + name + ' =====\n\n' + read(name)).join('\n');
const fontLicenses = Object.fromEntries(Object.entries({
  'ZTH Sans':'OFL.txt', 'ZCOOL XiaoWei':'ZCOOLXiaoWei-OFL.txt',
  'Ma Shan Zheng':'MaShanZheng-OFL.txt', 'Roboto Mono':'RobotoMono-OFL.txt'
}).map(([family, name]) => [family, read('app/assets/fonts/' + name)]));
const documents = [
  {id:'terms', title:'许可与使用说明 / Terms', file:'TERMS.txt', text:read('docs/TERMS.txt')},
  {id:'privacy', title:'隐私与本地数据 / Privacy', file:'PRIVACY.txt', text:read('docs/PRIVACY.txt')},
  {id:'license', title:'MIT 原始许可 / License', file:'LICENSE.txt', text:read('LICENSE')},
  {id:'third-party', title:'第三方原许可 / Third-party', file:'THIRD-PARTY-NOTICES.txt', text:thirdParty}
];
const output = new Map(documents.map(d => ['app/legal/' + d.file, d.text]));
output.set('app/legal-data.js', '// Generated by scripts/sync-legal.cjs. Edit docs/TERMS.txt or docs/PRIVACY.txt.\nwindow.ZTH_LEGAL_DOCUMENTS = ' + JSON.stringify(documents, null, 2) + ';\nwindow.ZTH_FONT_LICENSES = ' + JSON.stringify(fontLicenses, null, 2) + ';\n');
output.set('build/license.txt', 'ZTH Design Studio 4.0\n许可、隐私与开源授权 / License, Privacy and Open-source Notices\n\n' + documents.slice(0,3).map(d => d.text).join('\n\n====================\n\n') + '\n\n第三方完整许可随应用提供：设置 → 关于 → 许可与隐私 → 第三方原许可。\n随包副本：app/legal/THIRD-PARTY-NOTICES.txt；Windows 的 Electron / Chromium 许可另附于安装目录。\n');
const check = process.argv.includes('--check');
for (const [name, text] of output) {
  const destination = path.join(root, name);
  if (check) {
    if (!fs.existsSync(destination) || read(name) !== text) throw Error('Legal notices are out of date: ' + name);
  } else {
    fs.mkdirSync(path.dirname(destination), {recursive:true});
    fs.writeFileSync(destination, text, 'utf8');
  }
}
console.log(`${check ? 'Verified' : 'Synced'} ${output.size} legal documents with ${licensePaths.length} original third-party notices.`);
